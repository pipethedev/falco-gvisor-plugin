// Command gensysno generates per-architecture Linux syscall number tables
// from golang.org/x/sys/unix.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	sysModule   = "golang.org/x/sys"
	constPrefix = "SYS_"
	filePerm    = 0o644
)

var arches = []string{"amd64", "arm64"}

type syscallEntry struct {
	number uint64
	name   string
}

func main() {
	out := flag.String("out", ".", "output directory")
	pkg := flag.String("pkg", "gvisor", "package name")
	flag.Parse()

	dir, err := moduleDir(sysModule)
	if err != nil {
		log.Fatal(err)
	}
	for _, arch := range arches {
		if err := generate(dir, arch, *pkg, *out); err != nil {
			log.Fatal(err)
		}
	}
}

func moduleDir(module string) (string, error) {
	out, err := exec.CommandContext(context.Background(), "go", "mod", "download", "-json", module).Output()
	if err != nil {
		return "", fmt.Errorf("download %s: %w", module, err)
	}
	var info struct{ Dir string }
	if err := json.Unmarshal(out, &info); err != nil {
		return "", fmt.Errorf("decode %s download info: %w", module, err)
	}
	return info.Dir, nil
}

func generate(sysDir, arch, pkg, outDir string) error {
	src := filepath.Join(sysDir, "unix", "zsysnum_linux_"+arch+".go")
	entries, err := parseSyscalls(src)
	if err != nil {
		return err
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/gensysno from %s. DO NOT EDIT.\n\n", filepath.Base(src))
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	buf.WriteString("var syscallNames = map[uint64]string{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t%d: %q,\n", e.number, e.name)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", arch, err)
	}
	dst := filepath.Join(outDir, "sysno_"+arch+".go")
	if err := os.WriteFile(dst, formatted, filePerm); err != nil {
		return fmt.Errorf("write %s: %w", dst, err)
	}
	return nil
}

func parseSyscalls(path string) ([]syscallEntry, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	seen := map[uint64]bool{}
	var entries []syscallEntry
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			entry, ok := syscallFromSpec(spec)
			if !ok || seen[entry.number] {
				continue
			}
			seen[entry.number] = true
			entries = append(entries, entry)
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].number < entries[j].number })
	return entries, nil
}

func syscallFromSpec(spec ast.Spec) (syscallEntry, bool) {
	value, ok := spec.(*ast.ValueSpec)
	if !ok || len(value.Names) != 1 || len(value.Values) != 1 {
		return syscallEntry{}, false
	}
	name := value.Names[0].Name
	if !strings.HasPrefix(name, constPrefix) {
		return syscallEntry{}, false
	}
	lit, ok := value.Values[0].(*ast.BasicLit)
	if !ok || lit.Kind != token.INT {
		return syscallEntry{}, false
	}
	number, err := strconv.ParseUint(lit.Value, 0, 64)
	if err != nil {
		return syscallEntry{}, false
	}
	return syscallEntry{number: number, name: strings.ToLower(strings.TrimPrefix(name, constPrefix))}, true
}
