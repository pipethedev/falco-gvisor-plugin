#!/usr/bin/env bash
#
# Resolves mining pool hostnames into a Falco macro override that the
# "gVisor Connection to Known Mining Pool" rule uses.
#
#   rules/tools/pool_ips.sh [hosts-file] > /etc/falco/rules.d/gvisor_mining_pools.yaml
#
# Load the output after gvisor_rules.yaml. Pool addresses change often:
# regenerate it on a schedule (e.g. daily via cron or a CI job) and reload
# Falco (SIGHUP or watch_config_files).
set -euo pipefail

HOSTS_FILE="${1:-$(dirname "${BASH_SOURCE[0]}")/mining_pools.txt}"

resolve() {
  if command -v dig >/dev/null 2>&1; then
    { dig +short A "$1"; dig +short AAAA "$1"; } 2>/dev/null
  else
    getent ahosts "$1" 2>/dev/null | awk '{print $1}'
  fi
}

ips=$(grep -vE '^\s*(#|$)' "${HOSTS_FILE}" | while read -r host; do
  resolve "${host}"
done | grep -E '^[0-9a-fA-F:.]+$' | grep -vE '^(127\.|0\.|::1$)' | sort -u)

echo "# Generated by rules/tools/pool_ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) from ${HOSTS_FILE##*/}"
if [ -z "${ips}" ]; then
  echo "# No addresses resolved; the rule stays disabled."
  exit 0
fi
echo "- macro: gvisor_miner_pool_ip"
echo "  condition: >"
printf '    (fd.rip in ('
first=1
for ip in ${ips}; do
  if [ "${first}" -eq 0 ]; then printf ', '; fi
  printf '"%s"' "${ip}"
  first=0
done
echo '))'
echo "  override:"
echo "    condition: replace"
